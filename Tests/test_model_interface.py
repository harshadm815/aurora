"""The Brain's model interface: Ollama or AURORA's own model (Core Runtime)."""

import threading

import pytest

from aurora.brain.brain import Brain
from aurora.providers.base_provider import ModelUnavailableError
from aurora.providers.core_provider import CoreRuntimeProvider, checkpoint_path, core_models, prompt_from
from aurora.providers.model_switch import ModelSwitch
from aurora_core.tokenizer import ByteBPETokenizer
from aurora_core.training import save_checkpoint
from aurora_core.transformer import AuroraT0, T0Config

MESSAGES = [
    {"role": "system", "content": "You are AURORA."},
    {"role": "user", "content": "first message"},
    {"role": "assistant", "content": "a reply"},
    {"role": "user", "content": "Sherlock Holmes said"},
]


class FakeOllama:
    """Fails loudly if used: proves AURORA's model needs no Ollama."""

    def __init__(self, model="tinyllama", reachable=True):
        self.model = model
        self.reachable = reachable
        self.unloaded = []

    def chat(self, messages):
        return f"ollama:{self.model}"

    def chat_stream(self, messages):
        yield self.chat(messages)

    def health_check(self):
        if not self.reachable:
            raise ConnectionError("Ollama is not running")

    def installed_models(self):
        if not self.reachable:
            raise ConnectionError("Ollama is not running")
        return ["tinyllama:latest"]

    def unload(self, model=None):
        self.unloaded.append(model)


class FakeRuntime:
    def __init__(self, pieces=("Hello", " there", ".")):
        self.pieces = pieces
        self.loaded = False
        self.prompts = []
        self.cancelled = threading.Event()

    def load(self, path):
        self.loaded = True

        class Info:
            parameters = 1
        return Info()

    def unload(self):
        self.loaded = False

    def generate(self, prompt, config, on_text=None, cancel=None):
        self.prompts.append(prompt)
        for piece in self.pieces:
            if cancel is not None and cancel.wait(0.01):
                self.cancelled.set()
                return
            on_text(piece)


@pytest.fixture
def models_dir(tmp_path):
    """Models/tiny/best.npz: a real (untrained) checkpoint, plus a folder without one."""
    tok = ByteBPETokenizer()
    model = AuroraT0(T0Config(vocab_size=tok.vocab_size, context_length=16, d_model=16, n_heads=2,
                              dtype="float64", init_std=0.2), seed=2)
    (tmp_path / "tiny").mkdir()
    save_checkpoint(tmp_path / "tiny" / "best.npz", model, step=1, tokenizer=tok)
    (tmp_path / "empty").mkdir()
    return tmp_path


def test_lists_only_folders_with_a_checkpoint(models_dir):
    assert core_models(models_dir) == ["aurora:tiny"]
    assert core_models(models_dir / "missing") == []


@pytest.mark.parametrize("name", ["aurora:", "aurora:..", "aurora:../secrets", "aurora:a/b", "aurora:C:", "tinyllama"])
def test_model_names_cannot_leave_the_models_folder(models_dir, name):
    with pytest.raises(ModelUnavailableError):
        checkpoint_path(name, models_dir)


def test_prompt_is_the_latest_user_message():
    assert prompt_from(MESSAGES) == "Sherlock Holmes said"
    with pytest.raises(ModelUnavailableError):
        prompt_from([{"role": "system", "content": "x"}])


def test_ollama_is_used_for_ordinary_model_names():
    switch = ModelSwitch("tinyllama", ollama=FakeOllama())
    assert switch.chat(MESSAGES) == "ollama:tinyllama"
    switch.model = "phi3"
    assert switch.model == "phi3" and switch.chat(MESSAGES) == "ollama:phi3"


def test_brain_uses_the_switch_by_default():
    assert isinstance(Brain().provider, ModelSwitch)


def test_aurora_model_answers_without_ollama(models_dir):
    """A real checkpoint, generated by the real Core Runtime; Ollama is unreachable."""
    switch = ModelSwitch("aurora:tiny", ollama=FakeOllama(reachable=False), models_dir=models_dir)
    switch.health_check()
    reply = Brain(switch).ask(MESSAGES)

    assert isinstance(reply, str) and reply
    assert "�" not in reply
    assert switch.core.loaded
    assert switch.installed_models() == ["aurora:tiny"]


def test_only_the_latest_message_reaches_the_model(models_dir):
    runtime = FakeRuntime()
    switch = ModelSwitch("aurora:tiny", ollama=FakeOllama(), models_dir=models_dir,
                         core_factory=lambda name: CoreRuntimeProvider(name, models_dir, runtime=runtime))
    assert "".join(switch.chat_stream(MESSAGES)) == "Hello there."
    assert runtime.prompts == ["Sherlock Holmes said"]


def test_model_loads_lazily_and_switching_away_unloads_it(models_dir):
    runtime = FakeRuntime()
    switch = ModelSwitch("aurora:tiny", ollama=FakeOllama(), models_dir=models_dir,
                         core_factory=lambda name: CoreRuntimeProvider(name, models_dir, runtime=runtime))
    assert not runtime.loaded
    switch.chat(MESSAGES)
    assert runtime.loaded

    switch.model = "tinyllama"
    assert not runtime.loaded
    assert switch.core is None and switch.chat(MESSAGES) == "ollama:tinyllama"


def test_pause_unloads_the_aurora_model(models_dir):
    runtime = FakeRuntime()
    ollama = FakeOllama()
    switch = ModelSwitch("aurora:tiny", ollama=ollama, models_dir=models_dir,
                         core_factory=lambda name: CoreRuntimeProvider(name, models_dir, runtime=runtime))
    switch.chat(MESSAGES)
    switch.unload()
    assert not runtime.loaded and ollama.unloaded == []


def test_stopping_a_stream_early_stops_generation(models_dir):
    runtime = FakeRuntime(pieces=["x"] * 1000)
    provider = CoreRuntimeProvider("aurora:tiny", models_dir, runtime=runtime)
    stream = provider.chat_stream(MESSAGES)
    assert next(stream) == "x"
    stream.close()
    assert runtime.cancelled.wait(5)


def test_invalid_characters_are_not_shown(models_dir):
    runtime = FakeRuntime(pieces=["Hol", "�", "mes�"])
    provider = CoreRuntimeProvider("aurora:tiny", models_dir, runtime=runtime)
    assert provider.chat(MESSAGES) == "Holmes"


def test_missing_checkpoint_is_reported(models_dir):
    switch = ModelSwitch("aurora:empty", ollama=FakeOllama(), models_dir=models_dir)
    with pytest.raises(ModelUnavailableError, match="isn't on this PC"):
        switch.health_check()


def test_generation_errors_become_model_unavailable(models_dir):
    class Broken(FakeRuntime):
        def generate(self, *args, **kwargs):
            raise RuntimeError("boom")

    provider = CoreRuntimeProvider("aurora:tiny", models_dir, runtime=Broken())
    with pytest.raises(ModelUnavailableError, match="boom"):
        provider.chat(MESSAGES)


def test_ollama_being_down_is_still_reported_when_it_is_in_use(models_dir):
    switch = ModelSwitch("tinyllama", ollama=FakeOllama(reachable=False), models_dir=models_dir)
    with pytest.raises(ConnectionError):
        switch.installed_models()
