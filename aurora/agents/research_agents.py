"""
The research team.

Each agent has one job and works only through AURORA's tools and stores.
Nothing in a research report is generated by the language model:
everything is quoted from a named source, so it can be checked.
"""

import re

from aurora.agents.base import Agent, Blackboard
from aurora.agents.research_log import ResearchLog
from aurora.memory.manager import keywords
from aurora.tool_plugins.documents import Passage
from aurora.tools.untrusted import one_line

_VERSION = re.compile(r"v\d+$")
_QUESTION = re.compile(r"[^.!?\n]*\?|(?:open\s+question|todo|to\s+do|next\s+step)s?\s*[:\-][^\n]*", re.IGNORECASE)
_LABEL = re.compile(r"^(?:open\s+question|question|todo|to\s+do|next\s+step)s?\s*[:\-]\s*", re.IGNORECASE)

# Everyday words that say nothing about whether a paper is relevant.
_COMMON = set(keywords(
    "across about above after again against also among another around because before behave behaves "
    "being below between both could does each either even every event events from further give gives "
    "birth having here however into itself just less many more most much must near need other others "
    "over perhaps same several should show shows since some such than that their them then there these "
    "they this those through under until upon very whether which while will with within without would "
    "your study studies paper papers using used approach result results different angle work new first "
    "second third model models effect effects case cases based general"
))


def _meaningful(text: str) -> set[str]:
    return {w for w in keywords(text) if len(w) > 3 and w not in _COMMON}


def _as_written(stems: set[str], title: str) -> list[str]:
    """Matching words as they're spelled in the title ("entropy", not a stem)."""
    shown = []
    for word in re.findall(r"[A-Za-z][\w-]*", title):
        if keywords(word) and keywords(word)[0] in stems and word.lower() not in shown:
            shown.append(word.lower())
    return shown


def paper_id(url: str) -> str:
    """arXiv URL without its version, so v1 and v2 count as the same paper."""
    return _VERSION.sub("", url.strip())


class MemoryAgent(Agent):
    name = "Memory agent"
    icon = "🧠"
    task = "checking your research log and memories"

    def __init__(self, tools, log: ResearchLog):
        super().__init__(tools)
        self.log = log

    def run(self, board: Blackboard) -> None:
        project = self.log.find(board.topic)
        board.put("project", project)
        board.sources_ok.append("your research log")

        result = self.use_tool(board, "Recall", "your memory", query=board.topic)
        board.put("memories", list(result.data.matches) if result and result.data else [])


class DocumentsAgent(Agent):
    name = "Documents agent"
    icon = "📄"
    task = "searching your notes"

    MAX_FILES = 3
    MIN_PASSAGE_CHARS = 30

    def run(self, board: Blackboard) -> None:
        result = self.use_tool(board, "Documents", "your documents", action="search", query=board.topic)
        hits = list(result.data) if result and result.data else []

        # A note that mentions the topic is about the topic: use all of it,
        # not just the lines containing the topic's words.
        passages = []
        for name in list(dict.fromkeys(hit.file for hit in hits))[: self.MAX_FILES]:
            read = self.tools.execute("Documents", action="read", name=name) if self.tools else None
            text = read.data if read is not None and read.success and isinstance(read.data, str) else ""
            for paragraph in re.split(r"\n\s*\n", text):
                if len(paragraph.strip()) >= self.MIN_PASSAGE_CHARS:
                    passages.append(Passage(name, None, paragraph.strip()))
        board.put("passages", passages or hits)

        questions = []
        for passage in passages or hits:
            for match in _QUESTION.finditer(passage.text):
                question = _LABEL.sub("", one_line(match.group()))
                if len(question) > 8 and question not in questions:
                    questions.append(question)
        board.put("open_questions", questions[:5])


class ResearchAgent(Agent):
    name = "Research agent"
    icon = "🔭"
    task = "looking up background and new papers"

    def run(self, board: Blackboard) -> None:
        wiki = self.use_tool(board, "Wikipedia", "Wikipedia", topic=board.topic)
        if wiki and wiki.success:
            # Wikipedia's search returns its closest article even when it's off-topic.
            article = wiki.message.split(":", 1)[0]
            if _meaningful(board.topic) & _meaningful(wiki.message.split("\nSource:")[0]):
                board.put("background", wiki.message)
            else:
                board.problems.append(
                    f"Wikipedia's closest article (\"{article}\") isn't about this topic, so I left it out."
                )

        papers = self.use_tool(board, "arXiv", "arXiv", topic=board.topic, recent=True)
        found = list(papers.data) if papers and papers.success and papers.data else []

        project = board.get("project")
        seen = {paper_id(u) for u in project.seen_papers} if project else set()
        for paper in found:
            paper["new"] = paper_id(paper["url"]) not in seen
        board.put("papers", found)


class AnalystAgent(Agent):
    name = "Analyst agent"
    icon = "🧩"
    task = "comparing papers with your notes"

    def run(self, board: Blackboard) -> None:
        topic_words = set(keywords(board.topic))
        note_words = set()
        for passage in board.get("passages", []):
            note_words |= _meaningful(passage.text)
        for question in board.get("open_questions", []):
            note_words |= _meaningful(question)
        note_words -= topic_words   # Words beyond the topic itself are what make a paper relevant to *you*.

        papers = board.get("papers", [])
        for paper in papers:
            shared = note_words & _meaningful(f"{paper['title']} {paper.get('summary', '')}")
            in_title = _as_written(shared, paper["title"])
            # Prefer words visible in the title; fall back to the shared stems.
            paper["matches"] = (in_title or sorted(shared))[:4]
        papers.sort(key=lambda p: (not p["new"], -len(p["matches"])))

        steps = []
        new_papers = [p for p in papers if p["new"]]
        if new_papers:
            best = new_papers[0]
            verb = "appears" if len(best["matches"]) == 1 else "appear"
            reason = (f"it mentions {', '.join(best['matches'])}, which {verb} in your notes"
                      if best["matches"] else "it's the newest matching paper you haven't seen")
            steps.append(f"Read \"{best['title']}\": {reason}.")

        for question in board.get("open_questions", [])[:2]:
            words = _meaningful(question) - topic_words
            related = [p for p in papers if words & _meaningful(f"{p['title']} {p.get('summary', '')}")]
            if related:
                steps.append(f"For your open question \"{question}\", start with \"{related[0]['title']}\".")
            elif words:
                steps.append(f"No new paper addresses \"{question}\" yet; try: find papers on "
                             f"{board.topic} {' '.join(sorted(words)[:3])}")

        if not board.get("passages"):
            steps.append(f"Write your current hypothesis and open questions in a note in your Documents "
                         f"folder (for example {board.topic.replace(' ', '_')}.md), so I can compare "
                         "new papers with it next time.")
        if board.get("project") is None:
            steps.append("Start a research log for this topic (answer yes below), so next time I can "
                         "tell you which papers are new.")

        board.put("next_steps", steps[:4])


class ReviewerAgent(Agent):
    name = "Reviewer agent"
    icon = "✅"
    task = "checking sources"

    EXPECTED = ["your research log", "your memory", "your documents", "Wikipedia", "arXiv"]

    def run(self, board: Blackboard) -> None:
        answered = [s for s in self.EXPECTED if s in board.sources_ok]
        missing = [s for s in self.EXPECTED if s not in board.sources_ok]

        unsourced = [p["title"] for p in board.get("papers", []) if not p.get("url", "").startswith("http")]
        if unsourced:
            board.problems.append(f"{len(unsourced)} paper(s) had no link and were left out.")
            board.put("papers", [p for p in board.get("papers", []) if p.get("url", "").startswith("http")])

        board.put("review", {
            "answered": answered,
            "missing": missing,
            "complete": not missing,
        })
