"""
The claims register: every claim about AURORA's models, with its evidence.

``write_claims`` reads every docs/research/*/results.json and writes
docs/research/CLAIMS.md: what is claimed, the numbers, and the report
and runs that support it. Findings of "no detectable difference" are
listed too, so negative results aren't lost. Nothing is claimed that an
experiment didn't show under its own decision rule.
"""

import json
from pathlib import Path


def collect(root: Path) -> list[dict]:
    entries = []
    for path in sorted(Path(root).glob("*/results.json")):
        analysis = json.loads(path.read_text(encoding="utf-8"))
        folder = path.parent.name
        for variant in analysis.get("variants", []):
            comparison = variant.get("validation_comparison")
            if comparison is None:
                continue
            entries.append({
                "experiment": analysis["name"], "folder": folder, "variant": variant["name"],
                "baseline": analysis["baseline"], "verdict": variant.get("verdict", ""),
                "difference": comparison["mean_difference"], "ci": (comparison["ci_low"], comparison["ci_high"]),
                "n": comparison["n"], "complete": analysis.get("complete", False),
                "test": variant.get("test_confirmation"),
            })
        bigram = analysis.get("baseline_vs_bigram")
        if bigram:
            comparison = bigram["comparison"]
            entries.append({
                "experiment": analysis["name"], "folder": folder, "variant": f"{analysis['baseline']} vs bigram baseline (test)",
                "baseline": "bigram", "verdict": "beats the bigram baseline" if comparison["decision"] == "better" else comparison["decision"],
                "difference": comparison["mean_difference"], "ci": (comparison["ci_low"], comparison["ci_high"]),
                "n": comparison["n"], "complete": analysis.get("complete", False), "test": None,
            })
    return entries


def write_claims(root: Path) -> Path:
    entries = collect(root)
    lines = [
        "# Claims register",
        "",
        "Every claim about AURORA's own models, with the experiment that supports it. A claim is only listed as an",
        "improvement if its experiment's decision rule (fixed before running) was met on validation loss and confirmed",
        "on the test text. \"No detectable difference\" results are listed too. Differences are in nats of loss",
        "(negative = lower loss than the baseline), with 95 % confidence intervals over paired seeds.",
        "",
        "Generated by `python -m aurora_core.research claims` from `docs/research/*/results.json`.",
        "",
        "| Experiment | Change | Compared with | Difference [95 % CI] | Runs | Finding | Evidence |",
        "|---|---|---|---|---|---|---|",
    ]
    for entry in entries:
        low, high = entry["ci"]
        status = "" if entry["complete"] else " (incomplete)"
        lines.append(f"| {entry['experiment']} | {entry['variant']} | {entry['baseline']} | {entry['difference']:+.3f} "
                     f"[{low:+.3f}, {high:+.3f}] | {entry['n']} seeds | {entry['verdict']}{status} | "
                     f"[report]({entry['folder']}/report.md), [runs]({entry['folder']}/runs.jsonl) |")
    if not entries:
        lines.append("| — | — | — | — | — | No experiments recorded yet. | — |")
    path = Path(root) / "CLAIMS.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path
